#!/usr/bin/env node
/**
 * Regenerates src/evm/abi/ from forge artifacts of the Stealth contracts, one folder per build:
 *   CONTRACTS_OUT=/path/to/contracts/out npm run gen:abi
 * Writes each ABI as `export const xAbi = [...] as const`, so viem can infer its types.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.CONTRACTS_OUT;
if (!out) throw new Error("Set CONTRACTS_OUT to the contracts' forge out/ directory.");

const CONTRACTS = {
  StealthFactory: "stealthFactoryAbi",
  StealthFeeVault: "stealthFeeVaultAbi",
  StealthHook: "stealthHookAbi",
  StealthLocker: "stealthLockerAbi",
  StealthRouter: "stealthRouterAbi",
  StealthToken: "stealthTokenAbi",
  StealthTokenDeployer: "stealthTokenDeployerAbi",
};

for (const build of ["v4", "infinity"]) {
  const dir = join(here, "..", "src", "evm", "abi", build);
  mkdirSync(dir, { recursive: true });
  const lines = [];
  for (const [contract, name] of Object.entries(CONTRACTS)) {
    const { abi } = JSON.parse(readFileSync(join(out, build, `${contract}.sol`, `${contract}.json`), "utf8"));
    writeFileSync(join(dir, `${contract}.ts`), `// Generated by scripts/gen-abi.mjs. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 1)} as const;\n`);
    lines.push(`export { ${name} } from "./${contract}.js";`);
  }
  writeFileSync(join(dir, "index.ts"), `// Generated by scripts/gen-abi.mjs. Do not edit.\n${lines.join("\n")}\n`);
}
console.log("ABIs written.");
